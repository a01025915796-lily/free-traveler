export function getDestination(slug: string): Destination | undefined {
  return DESTINATIONS.find((d) => d.slug === slug);
}

export function getDestinationsByScope(scope: Scope): Destination[] {
  return DESTINATIONS.filter((d) => d.scope === scope);
}

export function getTheme(id: ThemeId): Theme {
  const theme = THEMES.find((t) => t.id === id);
  if (!theme) throw new Error(`Unknown theme: ${id}`);
  return theme;
}

export function getFeatured(scope: Scope): Destination[] {
  const slugs: readonly string[] = scope === "domestic" ? FEATURED_DOMESTIC : FEATURED_OVERSEAS;
  return slugs.map((slug) => {
    const destination = getDestination(slug);
    if (!destination) throw new Error(`Featured destination missing: ${slug}`);
    return destination;
  });
}
